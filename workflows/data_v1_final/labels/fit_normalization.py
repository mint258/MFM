"""Fit exact TRAIN-only winsorized statistics from pinned masked observations.

The observations are generated by the canonical label reader.  They remain
external artifacts.  Final mode requires independently frozen roles/common
membership and exact expected coverage; pilot output is explicitly nonfinal.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import math
import multiprocessing
import os
from pathlib import Path
import platform
import time

from common import read_json, reference, storage_preflight, verify_reference, write_json_new

CONTEXT = {}


def sqlstr(value):
    return "'" + str(value).replace("'", "''") + "'"


def init_worker(plan, files, output):
    CONTEXT.update(plan=plan, files=files, output=Path(output))


def element_reference(db, query, total_elements=118):
    """Fixed-order tall-skinny QR, with all atoms and an explicit intercept.

    This avoids squaring the condition number via normal equations.  Only
    TRAIN observations enter QR.  Rank and residual summaries are reported.
    """
    import numpy as np
    width = total_elements + 1
    r = np.empty((0, width), dtype=np.float64)
    rhs = np.empty((0,), dtype=np.float64)
    records = 0
    for batch in db.execute(query + " ORDER BY record_id").fetch_record_batch(4096):
        rows = batch.to_pylist()
        x = np.zeros((len(rows), width), dtype=np.float64)
        y = np.asarray([row["value"] for row in rows], dtype=np.float64)
        x[:, -1] = 1.0
        for i, row in enumerate(rows):
            z = row["atomic_numbers"]
            if not z or any(type(a) is not int or not 1 <= a <= total_elements for a in z):
                raise ValueError("ELEMENT_REFERENCE_REQUIRES_COMPLETE_ATOMIC_NUMBERS")
            x[i, :total_elements] = np.bincount(z, minlength=total_elements + 1)[1:]
        design = np.concatenate((r, x), axis=0)
        target = np.concatenate((rhs, y))
        q, r = np.linalg.qr(design, mode="reduced")
        rhs = q.T @ target
        records += len(rows)
    if not records:
        return None
    coef, _, rank, singular = np.linalg.lstsq(r, rhs, rcond=1e-12)
    return {"atomic_number_basis":list(range(1,119)), "coefficients":coef[:-1].tolist(),
        "intercept":float(coef[-1]),"fit_records":records,"rank":int(rank),
        "singular_values":singular.tolist(),"rcond":1e-12,
        "algorithm":"fixed record_id order, 4096-row TSQR, float64, intercept included",
        "element_identity_not_formula_only":True}


def rank_correlation(db, query):
    # Average ranks on the exact valid intersection, with null for constants.
    ranked = ("WITH a AS (" + query + "), b AS (SELECT *, "
        "rank() OVER(ORDER BY value)+(count(*) OVER(PARTITION BY value)-1)/2.0 AS ry, "
        "rank() OVER(ORDER BY heavy_atoms)+(count(*) OVER(PARTITION BY heavy_atoms)-1)/2.0 AS rx FROM a) "
        "SELECT count(*),corr(rx,ry) FROM b")
    n, rho = db.execute(ranked).fetchone()
    return {"status":"DEFINED" if rho is not None and math.isfinite(rho) else "UNDEFINED_CONSTANT_OR_TOO_FEW",
        "pair_n":n,"rho":rho if rho is not None and math.isfinite(rho) else None,
        "average_ties":True,"population":"TRAIN valid intersection, one molecule-level scalar per stored conformer"}


def fit_field(field):
    import duckdb
    import numpy as np
    plan = CONTEXT["plan"]
    scratch = CONTEXT["output"] / ("scratch_" + field["field_key"].replace(".", "_"))
    scratch.mkdir()
    db = duckdb.connect()
    db.execute("SET threads=1")
    db.execute("SET memory_limit=" + sqlstr(plan.get("per_worker_duckdb_memory", "1GB")))
    db.execute("SET temp_directory=" + sqlstr(scratch))
    db.execute("SET max_temp_directory_size=" + sqlstr(plan.get("per_worker_spill_limit", "2GiB")))
    files_sql = "[" + ",".join(sqlstr(x["path"]) for x in CONTEXT["files"]) + "]"
    role_path = plan["sources"]["frozen_record_manifest"]["path"]
    # Roles and diagnostic membership are read from the pinned final manifest.
    # Pre-mask parquet labels are never replaced by clipped/winsorized values.
    selected = ("SELECT o.*,r.atomic_numbers AS reference_atomic_numbers FROM read_parquet(" + files_sql + ",union_by_name=true) o "
        "JOIN read_parquet(" + sqlstr(role_path) + ") r USING(record_id) "
        "WHERE o.field_key=" + sqlstr(field["field_key"]) + " AND o.geometry_source=" + sqlstr(plan["geometry_source"]) +
        " AND upper(r.new_role)='TRAIN' AND r.common_population_v1 AND r.training_eligible "
        "AND o.molecule_id=r.molecule_id AND upper(o.new_role)=upper(r.new_role)")
    db.execute("CREATE VIEW selected_rows AS " + selected)
    record_n, unique_n = db.execute("SELECT count(*),count(DISTINCT record_id) FROM selected_rows").fetchone()
    if record_n != unique_n or record_n != plan["expected_fit_train_records"]:
        raise ValueError("NORMALIZATION_FIELD_RECORD_COVERAGE_DIFFERS:" + field["field_key"])
    query = ("SELECT o.record_id,o.molecule_id,o.reference_atomic_numbers AS atomic_numbers,"
        "list_count(list_filter(o.reference_atomic_numbers,z->z>1)) AS heavy_atoms,"
        "unnest(o.values_float64) AS value,unnest(o.value_mask) AS valid,unnest(o.element_z) AS element_z "
        "FROM selected_rows o")
    db.execute("CREATE VIEW raw AS SELECT * FROM (" + query + ") x WHERE valid AND isfinite(value)")
    count = db.execute("SELECT count(*) FROM raw").fetchone()[0]
    if count == 0:
        db.close()
        return {"field_key":field["field_key"],"status":"NO_VALID_TRAIN_VALUES","statistics":None}
    model = None
    if field["element_reference_eligible"]:
        model = element_reference(db, "SELECT record_id,value,atomic_numbers FROM raw")
        coefs = "[" + ",".join(repr(v) for v in model["coefficients"]) + "]"
        correction = "list_sum(list_transform(atomic_numbers,z->list_extract(" + coefs + ",z)))+" + repr(model["intercept"])
        db.execute("CREATE VIEW residual AS SELECT * REPLACE(value-(" + correction + ") AS value) FROM raw")
    else:
        db.execute("CREATE VIEW residual AS SELECT * FROM raw")
    low, high, median = db.execute("SELECT quantile_cont(value,0.001),quantile_cont(value,0.999),median(value) FROM residual").fetchone()
    mad = db.execute("SELECT median(abs(value-?)) FROM residual", [median]).fetchone()[0]
    stats = db.execute("SELECT count(*),avg(least(greatest(value,?),?)),stddev_pop(least(greatest(value,?),?)),min(value),max(value) FROM residual",[low,high,low,high]).fetchone()
    review_n = (db.execute("SELECT count(*) FROM residual WHERE 0.6744897501960817*abs(value-?)/?>20",[median,mad]).fetchone()[0]
                if mad > 0 else db.execute("SELECT count(*) FROM residual WHERE value<>?",[median]).fetchone()[0])
    per_element = []
    if field["level"] in ("atom", "atom_vector"):
        missing_z = db.execute("SELECT count(*) FROM residual WHERE element_z IS NULL").fetchone()[0]
        if missing_z:
            raise ValueError("PER_ELEMENT_STATISTICS_REQUIRE_ATOM_MAPPING:"+field["field_key"])
        zs = [row[0] for row in db.execute("SELECT DISTINCT element_z FROM residual ORDER BY element_z").fetchall()]
        for z in zs:
            lo, hi = db.execute("SELECT quantile_cont(value,0.001),quantile_cont(value,0.999) FROM residual WHERE element_z=?",[z]).fetchone()
            n, mean, std = db.execute("SELECT count(*),avg(least(greatest(value,?),?)),stddev_pop(least(greatest(value,?),?)) FROM residual WHERE element_z=?",[lo,hi,lo,hi,z]).fetchone()
            per_element.append({"atomic_number":z,"n":n,"winsor_lower":lo,"winsor_upper":hi,"mean":mean,"std_ddof0":std})
    rho = (rank_correlation(db,"SELECT value,heavy_atoms FROM residual") if field["level"]=="molecule" else
        {"status":"PENDING_VECTOR_OR_LOCAL_AGGREGATION_DEFINITION","rho":None,"pair_n":None})
    db.close()
    # No automatic deletion: the task guide retains existing files. DuckDB
    # closes its own temporary files; even empty scratch roots are retained.
    return {"field_key":field["field_key"],"status":"FIT_ON_DECLARED_TRAIN_SCOPE",
        "unit":field["unit"],"geometry_source":plan["geometry_source"],"element_reference":model,
        "statistics":{"n":stats[0],"winsor_lower_q001":low,"winsor_upper_q999":high,
            "mean":stats[1],"std_ddof0":stats[2],"unclipped_min":stats[3],"unclipped_max":stats[4],
            "median":median,"MAD":mad,"robust_z_gt20_review_count":review_n,
            "MAD_zero":mad==0,"zero_std":stats[2]==0,"labels_modified":False},
        "per_element_statistics":per_element,"TRAIN_heavy_atom_spearman":rho,
        "runtime":{"duckdb":duckdb.__version__,"numpy":np.__version__,"python":platform.python_version()}}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--plan",required=True)
    p.add_argument("--output",required=True)
    args=p.parse_args()
    plan=read_json(args.plan)
    if plan.get("schema_version")!="v1-label-normalization-plan.1":
        raise ValueError("UNKNOWN_NORMALIZATION_PLAN")
    if "SLURM_JOB_ID" not in os.environ or int(os.environ.get("SLURM_CPUS_PER_TASK","0"))<16:
        raise ValueError("NORMALIZATION_REQUIRES_16_CPU_SLURM")
    if os.uname().nodename.split(".")[0]!="compute-0-20":
        raise ValueError("NORMALIZATION_ANALYSIS_REQUIRES_DEFAULT_COMPUTE20")
    if int(plan.get("workers",0))!=16:
        raise ValueError("NORMALIZATION_REQUIRES_16_WORKERS")
    for ref in plan["sources"].values():
        verify_reference(ref)
    storage_preflight(plan)
    authority=read_json(plan["sources"]["split_authority"]["path"])
    if authority.get("status")!="FROZEN" or authority.get("all_conformers_same_role") is not True:
        raise ValueError("SPLIT_NOT_FROZEN; NO_FINAL_OR_PILOT_FIT_PERMITTED")
    if authority.get("validation_source")!="ROUTINE":
        raise ValueError("VAL_AUTHORITY_MUST_MATCH_USER_ROUTINE_DECISION")
    if plan.get("mode") not in ("pilot","final"):
        raise ValueError("EXPLICIT_PILOT_OR_FINAL_MODE_REQUIRED")
    files=read_json(plan["sources"]["observation_files"]["path"])
    for ref in files:
        verify_reference(ref)
    import duckdb
    db=duckdb.connect()
    rolepath=plan["sources"]["frozen_record_manifest"]["path"]
    names={row[0] for row in db.execute("DESCRIBE SELECT * FROM read_parquet("+sqlstr(rolepath)+")").fetchall()}
    required={"record_id","molecule_id","new_role","common_population_v1","training_eligible","atomic_numbers"}
    if not required<=names:
        raise ValueError("FROZEN_RECORD_MANIFEST_COLUMNS_MISSING:"+str(sorted(required-names)))
    n,unique=db.execute("SELECT count(*),count(DISTINCT record_id) FROM read_parquet("+sqlstr(rolepath)+")").fetchone()
    if n!=unique:
        raise ValueError("DUPLICATE_FROZEN_RECORD_ROLE")
    actual_train=db.execute("SELECT count(*) FROM read_parquet("+sqlstr(rolepath)+") WHERE upper(new_role)='TRAIN' AND common_population_v1 AND training_eligible").fetchone()[0]
    if actual_train!=int(plan.get("expected_fit_train_records",-1)) or actual_train<=0:
        raise ValueError("FIT_TRAIN_RECORD_COUNT_DIFFERS_FROM_PLAN")
    if plan["mode"]=="final" and (authority.get("common_population_frozen") is not True
            or plan.get("full_enabled_field_coverage_verified") is not True
            or plan.get("diagnostic_geometries_excluded") is not True):
        raise ValueError("FINAL_NORMALIZATION_POPULATION_OR_DIAGNOSTIC_COVERAGE_NOT_FROZEN")
    if plan["mode"]=="final" and actual_train!=int(authority.get("training_eligible_records",-1)):
        raise ValueError("FINAL_FIT_SCOPE_DIFFERS_FROM_FROZEN_AUTHORITY")
    db.close()
    fields=[f for f in read_json(plan["sources"]["registry"]["path"])["fields"] if f["status"]=="enabled"]
    output=Path(args.output).absolute()
    output.mkdir(parents=True,exist_ok=False)
    started=time.monotonic()
    results=[]
    try:
        with concurrent.futures.ProcessPoolExecutor(max_workers=16,mp_context=multiprocessing.get_context("spawn"),
                initializer=init_worker,initargs=(plan,files,str(output))) as pool:
            for result in pool.map(fit_field,fields,chunksize=1):
                results.append(result)
        write_json_new(output/"normalization.json",{"schema_version":"normalization_v1.0.0",
            "status":"PILOT_NOT_FINAL" if plan["mode"]=="pilot" else "FULL_DECLARED_TRAIN_SCOPE_FIT",
            "plan":reference(args.plan),"sources":plan["sources"],"mode":plan["mode"],"geometry_source":plan["geometry_source"],
            "slurm_job_id":os.environ["SLURM_JOB_ID"],"elapsed_seconds":time.monotonic()-started,
            "quantile_definition":"exact type-7 quantile_cont q=0.001 and 0.999",
            "winsorization":"statistics only; original training labels preserved",
            "robust_z":"review only, no automatic mask", "fields":results,
            "non_scalar_size_family_status":"PENDING_AGGREGATION_DEFINITION; NOT_FULL_REGISTRY_FREEZE",
            "determinism_scope":"same pinned inputs, record order, dependency versions, BLAS/thread settings; independent rerun bitwise check required"})
    except BaseException as exc:
        write_json_new(output/"normalization_failure.json",{"status":"FAILED_EVIDENCE_PRESERVED", "type":type(exc).__name__,"error":str(exc),"completed_fields":results})
        raise
    print("NORMALIZATION_"+plan["mode"].upper()+"_DONE",len(results))


if __name__=="__main__":
    main()
