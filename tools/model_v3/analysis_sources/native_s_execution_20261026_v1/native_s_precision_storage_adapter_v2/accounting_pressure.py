"""Bounded CPU operational-metadata stress; no training or data authority.

Prospective native-member identity in the Root request is a policy binding,
not an observation that this CPU process ran CUDA or decoded native records.
"""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import time

import native_s_storage as native
import profile_lifecycle


def materialize_and_measure(storage,output,limits,guard=lambda:None,*,maximum_output_bytes=2<<30):
    """Exercise real075 chain parsing and filesystem census at finite maxima.

    Every generated byte is labelled metadata pressure. No SDK, checkpoint,
    labels, source IDs, real quota feed or live counter ledger is copied.
    """
    output=storage.physical(output)
    storage.integer(limits['managed_roots'],'managed roots')
    storage.integer(limits['metadata_records'],'metadata records')
    storage.integer(limits['inode_limit'],'inode envelope')
    require=native.require
    require(not output.exists(),'Fresh pressure fixture root required')
    require(limits['metadata_records']>=limits['managed_roots']+8
        and limits['inode_limit']>=limits['metadata_records']+limits['managed_roots']+6,
        'Full metadata/root envelope must fit the declared inode limit')
    require(limits['metadata_bytes']<maximum_output_bytes-(64<<20),'Pressure bytes must fit inherited child cap/reserve')
    output.mkdir(mode=0o700,parents=True)
    root=output/'ledger_fixture'; root.mkdir()
    for name in ('records','index','roots','feeds','lineages'): (root/name).mkdir()
    managed=[root]
    for number in range(1,limits['managed_roots']):
        value=output/f'owned_fixture_root_{number:06d}'; value.mkdir(); managed.append(value)
    def raw_write(path,value):
        raw=storage.encoded(value)
        with path.open('xb') as stream: stream.write(raw)
        return dict(path=str(path),bytes=len(raw),sha256=__import__('hashlib').sha256(raw).hexdigest())
    for path in managed:
        raw_write(root/'roots'/(storage.canonical_hash(dict(path=str(path)))+'.json'),
            dict(path=str(path),kind='management',must_exist=True,type='directory'))
    count=(limits['metadata_records']-limits['managed_roots'])//2
    previous=None
    for number in range(1,count+1):
        if number%128==1: guard()
        row=dict(kind='observation',identity='ACCOUNTING_PRESSURE_FIXTURE_'+str(number),
            body=dict(operational_metadata_only=True,no_native_records_decoded=True))
        key=storage.canonical_hash(dict(kind=row['kind'],identity=row['identity']))
        ref=raw_write(root/'records'/(key+'.json'),row)
        previous=raw_write(root/'index'/f'{number:012d}.json',
            dict(sequence=number,previous=previous,record_ref=ref,record=row))
    for number in range(limits['metadata_records']-len(list(root.rglob('*.json')))):
        raw_write(root/f'metadata_capacity_fixture_{number}.json',dict(operational_metadata_only=True))
    size=storage.owned_bytes(root)
    require(size<=limits['metadata_bytes'],'Actual full chain bytes do not fit metadata policy')
    with (root/'metadata_bytes_capacity_fixture.bin').open('xb') as stream:
        remaining=limits['metadata_bytes']-size
        while remaining:
            guard(); block=min(1<<20,remaining); stream.write(b'\0'*block); remaining-=block
    # Distinct owned inodes, not repeated recounting of one small directory.
    entries=sum(1 for _ in output.rglob('*'))
    require(entries<=limits['inode_limit'],'Actual root/chain fixture exceeds inode policy')
    for number in range(limits['inode_limit']-entries):
        if number%128==0: guard()
        with (managed[number%len(managed)]/f'inode_capacity_fixture_{number:08d}.empty').open('xb'): pass
    reader=object.__new__(storage.DurableLedger); reader.root=root; reader.limits=limits
    durations=[]
    for _ in range(3):
        guard(); tick=time.perf_counter()
        #075 refresh contains repeated census/_space work. Exercise eight
        #complete real operations passes, label the composition explicitly.
        for _pass in range(8):
            rows=reader.records(); roots=reader.root_records()
            actual=sum(storage._runtime_census(Path(row['path'])) for row in roots)
            metadata_bytes=storage.owned_bytes(root)
            json_count=sum(1 for _ in root.rglob('*.json'))
            inodes=sum(1 for _ in output.rglob('*'))
        require(len(rows)==count and len(roots)==limits['managed_roots']
            and json_count==limits['metadata_records'] and metadata_bytes==limits['metadata_bytes']
            and inodes==limits['inode_limit'],'Pressure fixture failed to cover exact policy envelope')
        durations.append(time.perf_counter()-tick)
    return dict(managed_roots=len(roots),metadata_records=json_count,metadata_bytes=metadata_bytes,
        inode_entries=inodes,index_intents=len(rows),observed_runtime_bytes=actual,
        measured_seconds=max(durations),all_measured_seconds=durations,
        measurement_passes=8,
        measurement_scope='eight_real075_records_root_registry_distinct_root_census_metadata_space_passes; conservative_refresh_component_estimate',
        operational_metadata_only=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--request',type=Path,required=True); parser.add_argument('--request-sha256',required=True)
    parser.add_argument('--output',type=Path,required=True); parser.add_argument('--wall-seconds',type=int,default=600)
    args=parser.parse_args()
    native.require(os.environ.get('SLURM_JOB_ID') and int(os.environ.get('SLURM_CPUS_PER_TASK','0'))>=16,
        'Root-owned>=16CPU allocation required')
    native.require(not os.environ.get('CUDA_VISIBLE_DEVICES') and 60<=args.wall_seconds<=6900,
        'CPU-only pressure with explicitly bounded wall required')
    storage,pins=native.load_runtime(allow_candidate_profile=True); ref=storage.binding(args.request)
    native.require(ref['sha256']==args.request_sha256,'Exact Root pressure request raw SHA required')
    request=storage.read_bound(ref); configuration=storage.read_bound(request['configuration'])
    native.check_runtime_binding(request,configuration,pins)
    native.require(configuration['engineering_only'] is False and configuration['purpose']==native.PROFILE,
        'Actual Root operational profile-only quota required; no engineering authority')
    native.require(configuration['Root_runtime_pin']==native.runtime_pin(pins),'Combined accounting source pin differs')
    ledger=native.ledger_class(storage)(request,configuration)
    child_budget=profile_lifecycle.inherited_budget(ledger.limits['segment_bytes'])
    admission=ledger.admission['admission']
    native.require(admission['workload']=='native_S_accounting_pressure' and admission['operational_metadata_only'] is True
        and admission['pressure_runner_source']['sha256']==native.sha(__file__)
        and admission['pressure_wall_seconds']==args.wall_seconds,'Exact CPU metadata-pressure frame/source/wall required')
    target=storage.policy({'long_run_policy':configuration['pressure_target_policy']})
    storage.integer(configuration['pressure_overhead_inodes'],'pressure operational inode reserve')
    native.require(target['inode_limit']+configuration['pressure_overhead_inodes']<=ledger.limits['inode_limit'],
        'Separate bootstrap policy must cover stress fixture plus real accounting/SDK operational inodes')
    ledger.allocate_segment(request_ref=ref,segment_id=admission['segment_id'],job_root=args.output,
        lineage_root=admission['lineage_root'])
    native.require(not args.output.exists(),'Fresh pressure job root required')
    args.output.mkdir(mode=0o700,parents=True); started=time.monotonic(); refreshed=0.
    def guard():
        nonlocal refreshed
        native.require(time.monotonic()-started<args.wall_seconds-30,'Original pressure job wall reserve exceeded')
        if time.monotonic()-refreshed>=30:
            ledger.refresh(); refreshed=time.monotonic()
    result=materialize_and_measure(storage,args.output/'pressure_fixture',target,guard,maximum_output_bytes=child_budget)
    ledger.refresh()
    result.update(schema='native_S_accounting_pressure_v2',status='ACCOUNTING_CHILD_COMPLETED_PENDING_OUTER',
        Root_runtime_pin=native.runtime_pin(pins),scope=native.SCOPE,CPU_only=True,CUDA_or_native_record_execution=False,
        reservation_created_by_this_tool=False,scientific_acceptance=False,D5_authority=False)
    storage.write_once(args.output/'accounting_pressure.json',result)
    # Root alone releases the hold using its actual terminal/process closure.


if __name__=='__main__': main()
