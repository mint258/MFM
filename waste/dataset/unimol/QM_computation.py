# 配置日志记录
def setup_logging(output_directory, start_idx, end_idx):
    if not os.path.exists(output_directory):
        os.makedirs(output_directory)
    logging.basicConfig(
        filename=os.path.join(output_directory, f'compute_charge_{start_idx}_{end_idx}.log'),
        filemode='a',
        format='%(asctime)s - %(levelname)s - %(message)s',
        level=logging.INFO
    )

def read_xyz(file_path):
    """
    从XYZ文件读取 (num_atoms, atoms, coords).
    """
    with open(file_path, 'r') as f:
        lines = [l.strip() for l in f if l.strip()]
    num_atoms = int(lines[0])
    atoms = []
    coords = []
    for i in range(num_atoms):
        parts = lines[i + 2].split()
        atom = parts[0]
        x, y, z = map(float, parts[1:4])
        atoms.append(atom)
        coords.append((x, y, z))
    return num_atoms, atoms, np.array(coords)

def write_xyz(file_path, num_atoms, atoms, coords, scf_energy=None, charges=None):
    """
    将原子信息写回到XYZ文件中，包含SCF能量和电荷信息（可选）。
    """
    with open(file_path, 'w') as f:
        f.write(f"{num_atoms}\n")
        if scf_energy is not None:
            f.write(f"SCF Energy: {scf_energy:.8f} Hartree\n")
        else:
            f.write("Generated by compute_charge_sbatch.py\n")
        for i, (atom, (x, y, z)) in enumerate(zip(atoms, coords)):
            if charges is not None:
                f.write(f"{atom:2s}  {x:12.6f}  {y:12.6f}  {z:12.6f}  {charges[i]:12.6f}\n")
            else:
                f.write(f"{atom:2s}  {x:12.6f}  {y:12.6f}  {z:12.6f}\n")

def create_mopac_input(file_path, atoms, coords, output_directory, keyword="PM7 1SCF"):
    """
    创建MOPAC输入文件
    """
    base = os.path.splitext(os.path.basename(file_path))[0]
    input_file = os.path.abspath(os.path.join(output_directory, base + '.mop'))
    mol_str = f"{keyword}\n\n"
    mol_str += f"{base} - single point calculation\n"
    for atom, (x, y, z) in zip(atoms, coords):
        mol_str += f"{atom}   {x:.6f}   {y:.6f}   {z:.6f}\n"
    with open(input_file, 'w') as f:
        f.write(mol_str)
    return input_file

def submit_job(input_file, output_directory, cores, base):
    """
    创建并提交SLURM sbatch脚本，返回作业ID
    """
    sbatch_script = f"""#!/bin/bash
#SBATCH --job-name={base}
#SBATCH --output={output_directory}/{base}.out
#SBATCH --ntasks=1
#SBATCH --cpus-per-task={cores}
#SBATCH --time=02:00:00
#SBATCH --partition=cpu

mopac {input_file}
"""
    script_path = os.path.join(output_directory, f"{base}.sh")
    with open(script_path, 'w') as f:
        f.write(sbatch_script)
    
    # 提交作业并捕获作业ID
    result = subprocess.run(["sbatch", script_path], capture_output=True, text=True)
    if result.returncode != 0:
        logging.error(f"提交作业失败: {result.stderr}")
        raise RuntimeError(f"提交作业失败: {result.stderr}")
    
    # 从sbatch输出中提取作业ID
    match = re.search(r'Submitted batch job (\d+)', result.stdout)
    if match:
        job_id = match.group(1)
        # logging.info(f"提交作业成功: {base} (Job ID: {job_id})")
        return job_id
    else:
        logging.error(f"无法解析作业ID: {result.stdout}")
        raise RuntimeError(f"无法解析作业ID: {result.stdout}")

def check_output(output_file):
    """
    检查 MOPAC 输出文件是否包含所需的能量和电荷信息。
    """
    if not os.path.exists(output_file):
        return False

    with open(output_file, 'r') as f:
        content = f.read()

    has_energy = "FINAL HEAT OF FORMATION" in content
    has_charges = "NET ATOMIC CHARGES AND DIPOLE CONTRIBUTIONS" in content

    return has_energy and has_charges

def extract_results(output_file, atoms, coords, output_directory):
    """
    提取能量和电荷信息，并保存到 .xyz 文件。
    """
    with open(output_file, 'r') as f:
        lines = f.readlines()

    scf_energy = None
    charges = []
    for i, line in enumerate(lines):
        if "FINAL HEAT OF FORMATION" in line:
            match = re.search(r'(-?\d+\.\d+)', line)
            if match:
                scf_energy = float(match.group(1))
        if "NET ATOMIC CHARGES AND DIPOLE CONTRIBUTIONS" in line:
            start_index = i + 3
            for charge_line in lines[start_index:]:
                if not charge_line.strip() or "DIPOLE" in charge_line:
                    break
                parts = charge_line.split()
                try:
                    charge = float(parts[2])
                    charges.append(charge)
                except (IndexError, ValueError):
                    charges.append(0.0)  # 无法解析，默认为0.0

    if scf_energy is None:
        raise ValueError(f"文件 {output_file} 未找到 'FINAL HEAT OF FORMATION' 信息。")
    if len(charges) != len(atoms):
        raise ValueError(f"文件 {output_file} 的电荷数量与原子数量不匹配。")

    base = os.path.splitext(os.path.basename(output_file))[0]
    out_file = os.path.join(output_directory, base + ".xyz")
    with open(out_file, 'w') as outf:
        outf.write(f"{len(atoms)}\n")
        outf.write(f"SCF Energy: {scf_energy:.8f} Hartree\n")
        for (atom, (x, y, z)), charge in zip(zip(atoms, coords), charges):
            outf.write(f"{atom:2s}  {x:12.6f}  {y:12.6f}  {z:12.6f}  {charge:12.6f}\n")
    return scf_energy, charges

def has_geometry_error(output_file):
    """
    检查输出文件中是否包含 "GEOMETRY IN ERROR"。
    """
    if not os.path.exists(output_file):
        return False
    with open(output_file, 'r') as f:
        for line in f:
            if "GEOMETRY IN ERROR" in line:
                return True
    return False

def find_overlapping_atoms(atoms, coords, threshold=0.5):
    """
    查找所有重叠的原子对（距离小于阈值）。
    返回一个集合，包含需要重新分配坐标的原子索引。
    """
    num_atoms = len(atoms)
    # 计算距离矩阵
    diff = coords[:, np.newaxis, :] - coords[np.newaxis, :, :]  # (num_atoms, num_atoms, 3)
    distances = np.linalg.norm(diff, axis=2)  # (num_atoms, num_atoms)
    
    # 设置对角线为无穷大，避免自我对比
    np.fill_diagonal(distances, np.inf)
    
    # 识别距离小于阈值的原子对（包括不同原子间的零距离）
    overlapping = np.where(distances < threshold)
    
    # 提取需要重新分配坐标的原子索引
    overlapping_indices = set(overlapping[0]) | set(overlapping[1])
    
    return overlapping_indices

def generate_new_coordinate(existing_coords, min_val, max_val, threshold=0.5):
    """
    生成一个新的坐标，确保与现有坐标的距离大于阈值。
    """
    max_attempts = 100
    for _ in range(max_attempts):
        new_coord = np.array([
            np.random.uniform(min_val[0], max_val[0]),
            np.random.uniform(min_val[1], max_val[1]),
            np.random.uniform(min_val[2], max_val[2])
        ])
        distances = np.linalg.norm(existing_coords - new_coord, axis=1)
        if np.all(distances >= threshold):
            return new_coord
    raise RuntimeError("无法生成满足距离要求的新坐标。")

def fix_overlapping_atoms(atoms, coords):
    """
    修复重叠的原子坐标。
    """
    overlapping_indices = find_overlapping_atoms(atoms, coords, threshold=0.5)
    if not overlapping_indices:
        return coords  # 无需修复

    # 1. 计算每个轴上的最小和最大坐标
    x_min = coords[:, 0].min()
    x_max = coords[:, 0].max()
    y_min = coords[:, 1].min()
    y_max = coords[:, 1].max()
    z_min = coords[:, 2].min()
    z_max = coords[:, 2].max()

    # 2. 计算每个轴的坐标差值
    x_diff = x_max - x_min
    y_diff = y_max - y_min
    z_diff = z_max - z_min

    # 3. 选择最大的差值作为盒子尺寸
    box_size = max(x_diff, y_diff, z_diff)

    # 4. 根据盒子尺寸和坐标范围，计算每个轴的新坐标生成范围
    new_min_x = max(-box_size / 2, x_min)
    new_max_x = max(box_size / 2, x_max)
    new_min_y = max(-box_size / 2, y_min)
    new_max_y = max(box_size / 2, y_max)
    new_min_z = max(-box_size / 2, z_min)
    new_max_z = max(box_size / 2, z_max)

    # 定义新的坐标范围
    box_min = np.array([new_min_x, new_min_y, new_min_z])
    box_max = np.array([new_max_x, new_max_y, new_max_z])

    # 修复每个重叠的原子
    for idx in overlapping_indices:
        try:
            # 生成新的坐标，确保与所有其他原子的距离大于 0.5 Å
            new_coord = generate_new_coordinate(coords, box_min, box_max, threshold=0.5)
            coords[idx] = new_coord
            # logging.info(f"[Fix ] 重新分配原子 {idx + 1} 的坐标为 {new_coord}")
        except RuntimeError as e:
            logging.error(f"[Error] 修复原子 {idx + 1} 坐标失败: {e}")
            raise e

    return coords

def move_out_file(output_file, failed_dir):
    """
    将失败的输出文件移动到指定的失败目录。
    """
    if not os.path.exists(failed_dir):
        os.makedirs(failed_dir)
    base = os.path.basename(output_file)
    new_path = os.path.join(failed_dir, base)
    os.rename(output_file, new_path)
    logging.info(f"[Move ] 将失败的输出文件 {output_file} 移动到 {new_path}")

def process_completion(output_file, file_path, output_directory, max_retries, failed_dir, cores):
    """
    处理作业完成后的结果，检查输出，提取结果或进行重试。
    """
    base = os.path.splitext(os.path.basename(output_file))[0]
    try:
        if check_output(output_file):
            # 提取结果
            num_atoms, atoms, coords = read_xyz(file_path)
            extract_results(output_file, atoms, coords, output_directory)
            # 删除中间文件（除了 .xyz）
            files_to_remove = glob.glob(os.path.join(output_directory, f"{base}.*"))
            files_to_remove = [f for f in files_to_remove if not f.endswith(".xyz")]
            for file in files_to_remove:
                os.remove(file)
            logging.info(f"[OK   ] MOPAC计算完成，提取结果: {output_file}")
        elif has_geometry_error(output_file):
            # 发现几何错误，修复坐标并重新提交
            num_atoms, atoms, coords = read_xyz(file_path)
            coords = fix_overlapping_atoms(atoms, coords)
            write_xyz(file_path, num_atoms, atoms, coords)
            # 重新创建MOPAC输入文件，使用 PM7 进行几何优化
            input_file = create_mopac_input(file_path, atoms, coords, output_directory, keyword="PM7 1SCF")
            # 重新提交作业
            job_id = submit_job(input_file, output_directory, cores, base)
            logging.info(f"[Retry] 重新提交几何优化作业: {input_file} (Job ID: {job_id})")
        else:
            # 输出文件不完整，进行重试
            logging.warning(f"[Retry] 输出文件不完整: {output_file}")
            if os.path.exists(output_file):
                move_out_file(output_file, failed_dir)
            # 增加重试逻辑，如需要可以在这里重新提交作业
    except Exception as e:
        logging.error(f"[Error ] 处理作业完成时出错: {file_path}, 错误: {e}")
        if os.path.exists(output_file):
            move_out_file(output_file, failed_dir)

def get_current_jobs(user):
    """
    获取当前用户的所有作业ID
    """
    result = subprocess.run(["squeue", "-u", user, "-h", "-o", "%A"], capture_output=True, text=True)
    if result.returncode != 0:
        logging.error(f"获取作业列表失败: {result.stderr}")
        raise RuntimeError(f"获取作业列表失败: {result.stderr}")
    job_ids = result.stdout.strip().split('\n')
    return set(job_ids) if job_ids and job_ids[0] else set()

def submit_jobs(job_queue, running_jobs, running_jobs_lock, max_jobs, cores, output_directory, user, retries_dict):
    """
    作业提交线程函数
    """
    while not job_queue.empty():
        with running_jobs_lock:
            available_slots = max_jobs - len(running_jobs)
        if available_slots <= 0:
            time.sleep(0.1)
            continue
        try:
            file_path, retry_count = job_queue.get_nowait()
        except queue.Empty:
            break
        base = os.path.splitext(os.path.basename(file_path))[0]
        output_xyz = os.path.join(output_directory, f"{base}.xyz")
        if os.path.exists(output_xyz):
            # logging.info(f"[Skip] 已存在输出文件 {output_xyz}，跳过。")
            continue
        try:
            num_atoms, atoms, coords = read_xyz(file_path)
            input_file = create_mopac_input(file_path, atoms, coords, output_directory)
            job_id = submit_job(input_file, output_directory, cores, base)
            with running_jobs_lock:
                running_jobs[job_id] = (file_path, retry_count)
        except Exception as e:
            logging.error(f"[Error] 提交作业失败: {file_path}, 错误: {e}")
            if retry_count < 3:
                logging.info(f"[Retry] {file_path} 提交失败，准备重试 ({retry_count + 1}/3)")
                job_queue.put((file_path, retry_count + 1))
            else:
                logging.error(f"[Fail] {file_path} 提交失败，达到最大重试次数。")
                continue

def monitor_jobs(job_queue, running_jobs, running_jobs_lock, output_directory, max_retries, user, failed_dir, cores):
    """
    作业监控线程函数
    """
    count = 0
    while True:
        with running_jobs_lock:
            current_job_ids = get_current_jobs(user)
            completed_job_ids = [job_id for job_id in running_jobs if job_id not in current_job_ids]
        
        if not completed_job_ids and job_queue.empty() and not running_jobs:
            break  # 所有作业完成
        
        for job_id in completed_job_ids:
            with running_jobs_lock:
                file_path, retry_count = running_jobs.pop(job_id)
            base = os.path.splitext(os.path.basename(file_path))[0]
            output_file = os.path.join(output_directory, f"{base}.out")
            process_completion(output_file, file_path, output_directory, max_retries, failed_dir, cores)
            count += 1
            if count % 1000 == 0:
                logging.info(f"已经处理了 {count} 个结构")
        time.sleep(10)  # 调整检查间隔

def main(xyz_directory, output_directory, start_idx, end_idx, max_jobs, cores, user, structure_nums, save_wavefunctions=False):
    """
    主函数，批量提交并监控MOPAC作业
    """
    setup_logging(output_directory, start_idx, end_idx)

    # 使用二分法查找实际存在的最大分子序号
    low, high = start_idx, end_idx
    while low < high:
        mid = (low + high + 1) // 2
        file_path = os.path.join(xyz_directory, f"molecule_{mid:08}_10.xyz")
        if os.path.exists(file_path):
            low = mid
        else:
            high = mid -1

    # 实际最大分子序号
    actual_max_idx = low
    if end_idx > actual_max_idx:
        end_idx = actual_max_idx
        logging.info(f"指定的 end_idx 超出范围，已调整为实际最大序号 {end_idx}。")

    logging.info(f"处理分子序号范围：{start_idx} 至 {end_idx}。")

    # 生成所有相关的XYZ文件，并检查存在性
    job_queue = queue.Queue()
    for idx in range(start_idx, end_idx + 1):
        for struct_idx in range(1, structure_nums + 1):
            file_path = os.path.join(xyz_directory, f"molecule_{idx:08}_{struct_idx:02}.xyz")
            job_queue.put((file_path, 0))  # (file_path, retry_count)

    total_jobs = job_queue.qsize()
    logging.info(f"找到 {total_jobs} 个XYZ文件。")

    if total_jobs == 0:
        logging.info("没有需要处理的作业。")
        return

    # 初始化作业追踪字典和锁
    running_jobs = {}  # 作业ID: (file_path, retry_count)
    running_jobs_lock = threading.Lock()

    failed_dir = os.path.join(output_directory, "failed_outputs")
    if not os.path.exists(failed_dir):
        os.makedirs(failed_dir)

    # 创建并启动作业提交线程
    submit_thread = threading.Thread(target=submit_jobs, args=(job_queue, running_jobs, running_jobs_lock, max_jobs, cores, output_directory, user, {}))
    submit_thread.start()

    # 创建并启动作业监控线程
    monitor_thread = threading.Thread(target=monitor_jobs, args=(job_queue, running_jobs, running_jobs_lock, output_directory, 3, user, failed_dir, cores))
    monitor_thread.start()

    # 等待所有线程完成
    submit_thread.join()
    monitor_thread.join()

    logging.info("所有作业已处理完成。")

