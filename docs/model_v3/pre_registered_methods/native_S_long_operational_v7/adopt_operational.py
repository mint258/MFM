"""Root-only v7 operational adoption AFTER actual same-source CPU metadata QA.

No adoption file is shipped or generated by source preparation. This command
never invokes Slurm, imports a model, reads CP/SDK payload, or changes science.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from long_common import *
import quota_publish

TEST_NAMES=('test_long_contract.py','test_quota_retry.py','test_quota_publish.py')


def actual_CPU_QA(inputs,manifest):
    request=read_ref(inputs['unit_request']);summary=read_ref(inputs['summary'])
    unit=read_ref(inputs['unit_result']);supervisor=read_ref(inputs['supervisor'])
    raw=read_ref(inputs['actual_sacct']);job=summary['job_id']
    require(type(job) is str and job.isdigit() and raw['returncode']==0 and raw['stderr']==''
        and raw['argv']==['sacct','-X','-n','-P','-j',job,
            '--format=JobIDRaw,User,State,ExitCode,ElapsedRaw,AllocCPUS,NodeList'],
        'Actual exact-parent CPU accounting observation required')
    lines=[line.split('|') for line in raw['stdout'].splitlines() if line.strip()]
    require(len(lines)==1 and len(lines[0])==7 and lines[0][0]==job
        and lines[0][1:4]==['zixiao','COMPLETED','0:0'] and lines[0][4].isdigit()
        and int(lines[0][4])>0 and lines[0][5]=='16'
        and lines[0][6] in ['compute-0-'+str(i) for i in (2,*range(8,20))],
        'Owned actual16CPU C0 on a CPU node required')
    require(summary['status']=='PASS' and summary['node']==lines[0][6]
        and summary['cuda_visible_devices']=='' and summary['requested_cpus']=='16'
        and summary['request_sha256']==inputs['unit_request']['sha256']
        and summary['runner_sha256']==binding(OLD/'run_frozen_units_v1.py')['sha256'],
        'Actual original frozen-units CPU summary differs')
    require(request['schema']=='model_v3_frozen_units_request_v1'
        and unit in summary['units'] and unit['name']==inputs['unit_name']
        and unit['returncode']==0 and unit['sources_unchanged'] is True
        and unit['counts']==dict(tests=30,failures=0,errors=0,skipped=0),
        'Complete actual original8 plus v7 twenty-two metadata controls required')
    tasks=[row for row in request['tasks'] if row['name']==unit['name']]
    require(len(tasks)==1,'Exact actual CPU task required');task=tasks[0]
    require(task['tests']==[str(HERE/name) for name in TEST_NAMES]
        and task.get('environment',{}).get('PYTEST_ADDOPTS')=='-o tmp_path_retention_policy=failed',
        'Original three complete metadata modules/failed-only fixture policy required')
    before=unit['source_hashes_before']
    require(before==unit['source_hashes_after']==task['sources'],'Actual QA source-before/after differs')
    protected=[binding(HERE/row['path']) for row in read_ref(manifest)['files']]+[manifest]
    protected+=read(HERE/'dependency_pins.json')['references']
    for ref in protected:
        require(before.get(ref['path'])==ref['sha256'] and binding(ref['path'])==ref,
            'Actual same-source tested/current v7 or protected source absent/changed')
    xml_ref=inputs['JUnit'];require(binding(xml_ref['path'])==xml_ref,'Actual JUnit differs')
    argv=unit['argv'];expected=[summary['python_executable'],'-B','-m','pytest',
        *[str(HERE/name) for name in TEST_NAMES],'-q','-p','no:cacheprovider','--junitxml='+xml_ref['path']]
    require(argv[:-1]==expected and len(argv)==len(expected)+1 and argv[-1].startswith('--basetemp='),
        'Actual complete unfiltered pytest invocation differs')
    counts={key:0 for key in ('tests','failures','errors','skipped')}
    for suite in ET.fromstring(Path(xml_ref['path']).read_bytes()).iter('testsuite'):
        for key in counts:counts[key]+=int(suite.attrib.get(key,0))
    require(counts==unit['counts'],'Actual JUnit/JSON counts differ')
    require(supervisor['status']=='COMPLETED' and supervisor['exit_code']==0
        and str(supervisor['job_id'])==job and supervisor['first_failure'] is None
        and supervisor['remaining']==[] and supervisor['gpu_initialization_permitted'] is False
        and supervisor['private_storage']['first_sampling_failure'] is None,
        'Actual CPU supervisor/process/private cleanup incomplete')
    return dict(status='ACTUAL_C0_30_METADATA_TESTS_SOURCE_CLOSED',job_id=job,counts=counts,
        unit_request=inputs['unit_request'],summary=inputs['summary'],unit_result=inputs['unit_result'],
        JUnit=xml_ref,supervisor=inputs['supervisor'],actual_sacct=inputs['actual_sacct'],
        same_current_source_map_verified=True,science_acceptance=False)


def main():
    root_identity();parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--phase',type=Path,required=True);parser.add_argument('--pins-sha256',required=True)
    parser.add_argument('--inputs',type=Path,required=True);parser.add_argument('--inputs-sha256',required=True)
    args=parser.parse_args();manifest,_=verify(args.pins_sha256)
    input_ref=binding(args.inputs);require(input_ref['sha256']==args.inputs_sha256,'Actual Root input rawSHA required')
    inputs=read_ref(input_ref)
    require(inputs['schema']=='native_S_long_v7_adoption_inputs_v1','Explicit post-QA Root metadata inputs required')
    qa=actual_CPU_QA(inputs,manifest)
    from long_operations import lock,closed_attempts,next_member
    phase=args.phase.absolute()
    require(phase==N/'native_S_B20k_v3','Only the already-running17000 lineage may adopt this narrow v7')
    with lock(phase):
        require(not (phase/'control/OPERATIONAL_ADOPTION_v7.json').exists(),'v7 adoption already exists; never overwrite')
        original=binding(phase/'control/VALIDATED.json');validated=read_ref(original)
        prior_ref=binding(phase/'control/OPERATIONAL_ADOPTION_v4.json');prior=read_ref(prior_ref)
        require(prior['schema']=='native_S_long_operational_adoption_v4'
            and prior['original_validation']==original and prior['original_package']==validated['package_manifest']
            and prior['package_manifest']==binding(N/'native_S_long_operational_v4/source_pins.json'),
            'Actual original validation and adopted v4 sources differ')
        for name in ('configuration','profile','initial_roots','runtime_contract','registry'):
            require(prior[name]==validated[name],'Original science/evidence/registry identity changed')
        for name in ('configuration','profile','initial_roots','runtime_contract'):read_ref(validated[name])
        principal=binding(phase/'control/principal.json');require(principal==prior['principal'],'Original principal changed')
        attempts=closed_attempts(phase);next_step=next_member(phase)
        good=[row for row in attempts if row[1]['status']=='OUTER_C0_SEGMENT_CLOSED_SDK_PENDING']
        require(len(attempts)==18 and len(good)==17
            and (next_step['slot'],next_step['seed'],next_step['precision'],next_step['start_update'],next_step['target_update'])
                ==(19,0,'fp32',17000,18000) and next_step['resume_checkpoint'] is not None,
            'Existing eighteen attempts/seventeen successes/safe17000 continuation differs')
        old_lease=binding(phase/'control/leases/slot_019.json')
        require(old_lease==inputs['orphan_lease'],'Original orphan019 lease changed')
        old=read_ref(old_lease)
        require(old['reservation_id']==phase.name and old['authority']=='ROOT_ACTUAL','Original lease identity differs')
        occupied=dict(intent=(phase/'control/attempts/slot_019.intent.json').exists(),
            submitted=(phase/'control/attempts/slot_019.submitted.json').exists(),
            script=(OLD/(phase.name+'_slot_019.sbatch')).exists(),slot_root=slot_layout(phase,19)['root'].exists())
        require(not any(occupied.values()),'Unresolved slot019 evidence; Root must reconcile, never auto-retry')
        require(inputs['coordinator_pid']==3190990 and not Path('/proc/3190990').exists(),
            'Old coordinator present/reused; explicit Root reconciliation required')
        log_ref=inputs['failed_coordinator_stdout']
        require(log_ref['path']==str(phase/'control/Root_slot019_coordinator_resume_20261029_v1.stdout.log')
            and binding(log_ref['path'])==log_ref,'Actual prior failure log differs')
        text=Path(log_ref['path']).read_text()
        require("KeyError: 'durable_root'" in text and 'root_phase.py' in text and 'long_operations.py' in text,
            'Exact observed publisher compatibility failure required')
        # Keep the real v5 adoption/QA/failure as a separately bound history.
        # It did not submit, create a fresh lease, or consume another slot.
        previous_ref=inputs['failed_v5_adoption']
        require(previous_ref==binding(phase/'control/OPERATIONAL_ADOPTION_v5.json'),
            'Exact retained actual v5 adoption required')
        previous=read_ref(previous_ref);previous_package=binding(N/'native_S_long_operational_v5/source_pins.json')
        require(previous['schema']=='native_S_long_operational_adoption_v5'
            and previous['authority']=='ROOT_ACTUAL' and previous['original_validation']==original
            and previous['original_package']==validated['package_manifest']
            and previous['prior_operational_adoption']==prior_ref
            and previous['package_manifest']==previous_package and previous['principal']==principal
            and previous['counters_reset'] is False
            and previous['numerical_science_config_data_seed_precision_unchanged'] is True,
            'Actual failed v5 operational/source/main-chain identity differs')
        for name in ('configuration','profile','initial_roots','runtime_contract','registry'):
            require(previous[name]==validated[name],'Failed v5 adoption changed original binding')
        old_qa=previous['actual_CPU_QA']
        require(old_qa['status']=='ACTUAL_C0_23_METADATA_TESTS_SOURCE_CLOSED'
            and old_qa['counts']==dict(tests=23,failures=0,errors=0,skipped=0)
            and read_ref(old_qa['summary'])['status']=='PASS'
            and read_ref(old_qa['unit_result'])['counts']==old_qa['counts'],
            'Retained actual v5 same-source23 metadata QA differs')
        for row in read_ref(previous_package)['files']:
            actual_ref=binding(N/'native_S_long_operational_v5'/row['path'])
            require(actual_ref['bytes']==row['bytes'] and actual_ref['sha256']==row['sha256'],
                'Frozen v5 source history changed')
        require(previous['orphan_prelaunch']['lease']==old_lease
            and previous['orphan_prelaunch']['failed_coordinator_stdout']==log_ref
            and previous['orphan_prelaunch']['coordinator_pid']==3190990
            and previous['orphan_prelaunch']['source_failure_before_sbatch'] is True,
            'Failed v5 orphan019 history differs')
        require(type(inputs['failed_v5_coordinator_pid']) is int
            and inputs['failed_v5_coordinator_pid']==3201293 and not Path('/proc/3201293').exists(),
            'Failed v5 coordinator present/reused; explicit Root reconciliation required')
        previous_log=inputs['failed_v5_coordinator_stdout']
        require(previous_log['path']==str(phase/'control/Root_slot019_coordinator_v5_20261029_v1.stdout.log')
            and binding(previous_log['path'])==previous_log,'Actual retained v5 failure log differs')
        previous_text=Path(previous_log['path']).read_text()
        require("KeyError: 'initial_existing_bytes'" in previous_text
            and 'quota_publish.py' in previous_text and 'long_operations.py' in previous_text,
            'Exact observed historical panel compatibility failure required')
        require(not (phase/'control/leases/slot_019.operational_v5.json').exists(),
            'Unexpected failed-v5 fresh lease requires Root reconciliation')
        # v6 passed its own30-test CPU QA but failed before new lease/SBATCH:
        # a plain-text log rawref was accidentally sent to the JSON reader.
        previous6_ref=inputs['failed_v6_adoption']
        require(previous6_ref==binding(phase/'control/OPERATIONAL_ADOPTION_v6.json'),
            'Exact retained actual v6 adoption required')
        previous6=read_ref(previous6_ref);previous6_package=binding(N/'native_S_long_operational_v6/source_pins.json')
        require(previous6['schema']=='native_S_long_operational_adoption_v6'
            and previous6['authority']=='ROOT_ACTUAL' and previous6['original_validation']==original
            and previous6['original_package']==validated['package_manifest']
            and previous6['prior_operational_adoption']==prior_ref
            and previous6['package_manifest']==previous6_package and previous6['principal']==principal
            and previous6['failed_v5_operational_adoption']==previous_ref
            and previous6['failed_v5_package_manifest']==previous_package
            and previous6['failed_v5_coordinator_stdout']==previous_log
            and previous6['counters_reset'] is False
            and previous6['numerical_science_config_data_seed_precision_unchanged'] is True,
            'Actual failed v6 operational/source/main-chain identity differs')
        for name in ('configuration','profile','initial_roots','runtime_contract','registry'):
            require(previous6[name]==validated[name],'Failed v6 adoption changed original binding')
        old6_qa=previous6['actual_CPU_QA']
        require(old6_qa['status']=='ACTUAL_C0_30_METADATA_TESTS_SOURCE_CLOSED'
            and old6_qa['job_id']=='4524703'
            and old6_qa['counts']==dict(tests=30,failures=0,errors=0,skipped=0)
            and read_ref(old6_qa['summary'])['status']=='PASS'
            and read_ref(old6_qa['unit_result'])['counts']==old6_qa['counts'],
            'Retained actual v6 CPU4703 same-source30 metadata QA differs')
        for row in read_ref(previous6_package)['files']:
            actual_ref=binding(N/'native_S_long_operational_v6'/row['path'])
            require(actual_ref['bytes']==row['bytes'] and actual_ref['sha256']==row['sha256'],
                'Frozen v6 source history changed')
        require(previous6['orphan_prelaunch']['lease']==old_lease
            and previous6['orphan_prelaunch']['failed_coordinator_stdout']==log_ref,
            'Failed v6 orphan019 history differs')
        require(type(inputs['failed_v6_coordinator_pid']) is int
            and inputs['failed_v6_coordinator_pid']==3204269 and not Path('/proc/3204269').exists(),
            'Failed v6 coordinator present/reused; explicit Root reconciliation required')
        previous6_log=inputs['failed_v6_coordinator_stdout']
        require(previous6_log['path']==str(phase/'control/Root_slot019_coordinator_v6_20261029_v1.stdout.log')
            and binding(previous6_log['path'])==previous6_log,'Actual retained v6 failure log differs')
        previous6_text=Path(previous6_log['path']).read_text()
        require('JSONDecodeError' in previous6_text and 'long_operations.py' in previous6_text
            and 'common.py' in previous6_text and 'read_ref' in previous6_text,
            'Exact observed plain-text-log JSON-reader failure required')
        require(not (phase/'control/leases/slot_019.operational_v6.json').exists(),
            'Unexpected failed-v6 fresh lease requires Root reconciliation')
        descriptor=quota_publish.ensure_descriptor(phase)
        result=write(phase/'control/OPERATIONAL_ADOPTION_v7.json',dict(
            schema='native_S_long_operational_adoption_v7',authority='ROOT_ACTUAL',original_validation=original,
            original_package=validated['package_manifest'],prior_operational_adoption=prior_ref,package_manifest=manifest,
            configuration=validated['configuration'],profile=validated['profile'],initial_roots=validated['initial_roots'],
            runtime_contract=validated['runtime_contract'],principal=principal,registry=validated['registry'],
            original_failed_closure=prior['original_failed_closure'],quota_feed_descriptor=descriptor,
            actual_CPU_QA=qa,Root_inputs=input_ref,failed_v5_operational_adoption=previous_ref,
            failed_v5_package_manifest=previous_package,failed_v5_coordinator_stdout=previous_log,
            failed_v5_coordinator_pid=3201293,failed_v5_no_fresh_lease_intent_submission_or_slot=True,
            failed_v6_operational_adoption=previous6_ref,failed_v6_package_manifest=previous6_package,
            failed_v6_coordinator_stdout=previous6_log,failed_v6_coordinator_pid=3204269,
            failed_v6_no_fresh_lease_intent_submission_or_slot=True,
            orphan_prelaunch=dict(slot=19,lease=old_lease,failed_coordinator_stdout=log_ref,
                coordinator_pid=3190990,source_failure_before_sbatch=True,old_files_not_rewritten=True),
            historical_attempt_refs=[dict(submission=binding(phase/'control/attempts'/f'slot_{row[0]["slot"]:03d}.submitted.json'),
                closure=row[2]) for row in attempts],next_step_at_adoption=next_step,
            science_code_sha=CODE,science_prereg_sha=PUBLIC,numerical_science_config_data_seed_precision_unchanged=True,
            counters_reset=False,no_new_reservation_or_model_started=True,scientific_acceptance=False,
            operational_changes=['plain_text_failure_log_raw_binding_not_JSON_read',
                'exact_closed_zero_historical_panel_one_job_variant',
                'typed_budget_projection_all_holds_no_foreign_ledger',
                'new_quota_producer_descriptor_and_feed_old_records_retained',
                'explicit_unsubmitted_orphan019_lease_reuse_or_fresh_distinct_path']))
        print(json.dumps(dict(status='OPERATIONAL_V7_ADOPTED_NO_SUBMISSION',adoption=result,next=next_step)))
    return 0


if __name__=='__main__':raise SystemExit(main())
